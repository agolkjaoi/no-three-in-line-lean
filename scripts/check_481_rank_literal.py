"""Check the Lean rank literal against the archived 481-phase binary table."""

import argparse
import re
from hashlib import sha256
from pathlib import Path
from struct import iter_unpack

TYPE_COUNT = 4
GRID = 256
COARSE_GRID = 16
PHASE_COUNT = 481
BLOCK_SIZE = 1024
DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUV"


def expected_source(root: Path) -> bytes:
    data = root / "docs/paper/481-phase/verification/data"
    binary = (data / "full_rank.bin").read_bytes()
    ranks = [rank for (rank,) in iter_unpack("<i", binary)]
    if len(ranks) != TYPE_COUNT * GRID**2:
        raise ValueError(f"unexpected rank count: {len(ranks)}")

    units = list(map(int, (data / "field_units.txt").read_text(encoding="ascii").split()))
    frozen = (root / "NoThreeLine/FrozenCapacityData.lean").read_text(encoding="utf-8")
    frozen_tables = re.findall(
        r"def type[0-3] : FiniteInputTree ℤ 256 :=\n(.*?)\ntheorem type[0-3]_nonneg",
        frozen, flags=re.S,
    )
    frozen_units = [
        int(unit) for table in frozen_tables for unit in re.findall(r"\.single (\d+)\)", table)
    ]
    if len(units) != TYPE_COUNT * COARSE_GRID**2 or units != frozen_units:
        raise ValueError("published field units differ from the Lean coarse table")

    subdivisions = GRID // COARSE_GRID
    active = set()
    positive = 0
    encoded = []
    for index, rank in enumerate(ranks):
        typ, xy = divmod(index, GRID**2)
        x, y = divmod(xy, GRID)
        weight = units[
            typ * COARSE_GRID**2 + (x // subdivisions) * COARSE_GRID + y // subdivisions
        ]
        if weight > 0:
            if not 0 <= rank < PHASE_COUNT:
                raise ValueError(f"invalid positive-cell rank at index {index}: {rank}")
            active.add(rank)
            positive += 1
        elif rank != -1:
            raise ValueError(f"expected the zero-cell sentinel at index {index}")
        code = 511 if rank == -1 else rank
        encoded.append(DIGITS[code // 32] + DIGITS[code % 32])
    if len(active) != PHASE_COUNT or positive != 242_176:
        raise ValueError("unexpected number of positive cells or nonempty ranks")

    blocks = [
        '  "' + "".join(encoded[start:start + BLOCK_SIZE]) + '"'
        for start in range(0, len(encoded), BLOCK_SIZE)
    ]
    header = (
        "/-! Generated by scripts/check_481_rank_literal.py from the 481-phase rank table.\n"
        f"Source SHA-256: {sha256(binary).hexdigest()}.\n"
        "Each entry has two radix-32 digits. Code 511 denotes the zero-cell sentinel. -/\n\n"
        "namespace NoThreeLine481\n\n"
        "def rankBlocks : Array String := #[\n"
    )
    return (header + ",\n".join(blocks) + "\n]\n\nend NoThreeLine481\n").encode("ascii")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the Lean literal")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output = root / "NoThreeLine481/RankData.lean"
    expected = expected_source(root)
    if args.write:
        output.write_bytes(expected)
    if output.read_bytes() != expected:
        raise SystemExit("Lean rank literal differs from the archived input")
    print("481 ranks, 242176 positive cells, and all 1024 field units match the archived input")


if __name__ == "__main__":
    main()
